import type {
  CharacterCategory,
  CharacterProfile,
  EmblemTheme,
} from "@battle-arena/shared";

/**
 * Curated Battle Arena roster.
 *
 * This is the Phase A/B source of truth so the battle flow works offline and
 * deterministically. Every profile carries the attributes the simulation engine
 * consumes, plus the evidence label shown on the profile page. The Phase E
 * research pipeline writes additional profiles into the database; the API
 * already prefers a database record when one exists.
 *
 * Historical-category fighters are real-world figures, living or historical;
 * their attributes describe documented equipment and public records, never
 * invented superhuman abilities.
 */

interface RosterEntry {
  id: string;
  name: string;
  aliases?: string[];
  universe: string;
  franchise?: string;
  category: CharacterCategory;
  origin: string;
  era?: string;
  description: string;
  /** strategic, tactical, problemSolving, adaptability, experience, prediction, deception, decisionMaking, resourceManagement */
  i: [number, number, number, number, number, number, number, number, number];
  /** strength, attackPower, speed, reactionSpeed, durability, defence, stamina, endurance, combatSkill */
  c: [number, number, number, number, number, number, number, number, number];
  abilities: string[];
  weaknesses: string[];
  weaknessTags?: string[];
  equipment?: string[];
  resistances?: string[];
  feats: string[];
  evidence?: string[];
  tags: string[];
  theme: EmblemTheme;
}

function build(entry: RosterEntry): CharacterProfile {
  const [strategic, tactical, problemSolving, adaptability, experience, prediction, deception, decisionMaking, resourceManagement] = entry.i;
  const [strength, attackPower, speed, reactionSpeed, durability, defence, stamina, endurance, combatSkill] = entry.c;

  return {
    id: entry.id,
    name: entry.name,
    aliases: entry.aliases ?? [],
    universe: entry.universe,
    franchise: entry.franchise ?? null,
    category: entry.category,
    origin: entry.origin,
    era: entry.era ?? null,
    description: entry.description,
    intelligence: {
      strategic,
      tactical,
      problemSolving,
      adaptability,
      experience,
      prediction,
      deception,
      decisionMaking,
      resourceManagement,
    },
    combat: {
      strength,
      attackPower,
      speed,
      reactionSpeed,
      durability,
      defence,
      stamina,
      endurance,
      combatSkill,
    },
    abilities: entry.abilities,
    weaknesses: entry.weaknesses,
    weaknessTags: entry.weaknessTags ?? [],
    equipment: entry.equipment ?? [],
    resistances: entry.resistances ?? [],
    feats: entry.feats,
    evidence: entry.evidence ?? ["Canon source material"],
    tags: entry.tags,
    theme: entry.theme,
  };
}

